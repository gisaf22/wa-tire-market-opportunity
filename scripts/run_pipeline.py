"""Pulls -> build -> model -> evaluation -> signals. Writes data/processed/ and reports/.

Usage (from the repo root):
    python3 scripts/run_pipeline.py            # uses cached raw pulls in data/raw/ if present
    python3 scripts/run_pipeline.py --refresh  # re-pull WA DOR, DOL and BLS
"""

import argparse
import datetime as dt

from wa_tire import build, config, evaluate, model, pull_cpi, pull_demand, pull_wa, signals


def md_table(df, floatfmt=".3f"):
    return df.to_markdown(index=False, floatfmt=floatfmt)


def main(refresh):
    config.PROCESSED.mkdir(parents=True, exist_ok=True)
    config.REPORTS.mkdir(parents=True, exist_ok=True)

    print("1/5 pulls")
    raw, locs = pull_wa.pull_sales(refresh=refresh)
    vehicles = pull_demand.pull_registrations(refresh=refresh)
    cpi = pull_cpi.pull_cpi(int(config.FIRST_QUARTER[:4]), dt.date.today().year, refresh=refresh)
    deflators = pull_cpi.quarterly_deflators(cpi)

    print("2/5 build")
    quarters = sorted(raw["quarter"].unique())
    cq = build.deflate(build.county_quarter(raw, locs, quarters), deflators)
    cy = build.county_year(cq, vehicles)
    excl = build.exclusions(cq, cy)
    included = sorted(excl.loc[~excl["excluded"], "county"])
    coverage = build.coverage_table(cq, cy, excl)
    transition = build.naics_transition_check(cq)
    outliers = build.qoq_outliers(cq, included)

    print("3/5 model")
    df = model.model_frame(cy, included)
    fit_split, test_pred = model.run_split(df)
    fit_full, full_pred = model.run_full(df)

    print("4/5 evaluate")
    ev = evaluate.evaluation_table(test_pred)
    ev_year = evaluate.evaluation_by_year(test_pred)

    print("5/5 signals")
    last = int(cy["year"].max())
    recent = list(range(last - config.RECENT_YEARS_N + 1, last + 1))
    res = signals.residuals(full_pred, recent)
    gap = signals.growth_gap(cy[cy["county"].isin(included)], config.GROWTH_BASE_YEAR, last)
    ranked = signals.rank_and_flag(res, gap, config.TOP_SHARE)

    outputs = {
        "county_quarter": cq, "county_year": cy, "exclusions": excl, "coverage": coverage,
        "naics_transition_check": transition, "qoq_outliers": outliers, "cpi_quarterly": deflators,
        "test_predictions": test_pred, "full_predictions": full_pred,
        "evaluation": ev, "evaluation_by_year": ev_year,
        "coefficients_train": model.coefficient_table(fit_split).reset_index(names="term"),
        "coefficients_full": model.coefficient_table(fit_full).reset_index(names="term"),
        "signals": ranked,
    }
    for name, frame in outputs.items():
        frame.to_csv(config.PROCESSED / f"{name}.csv", index=False)
    locs.to_csv(config.REPORTS / "location_codes.csv", index=False)

    top = ranked[ranked["top_candidate"]]
    summary = [
        "# Pipeline results (generated by scripts/run_pipeline.py)\n",
        f"Run date: {dt.date.today()}. Sales quarters: {quarters[0]}-{quarters[-1]}. "
        f"Model years: {config.MODEL_FIRST_YEAR}-{last} (train {min(config.TRAIN_YEARS)}-{max(config.TRAIN_YEARS)}, "
        f"test {config.TEST_FIRST_YEAR}-{last}). Residuals averaged over {recent[0]}-{recent[-1]}; "
        f"growth gap {config.GROWTH_BASE_YEAR}-{last}.\n",
        f"Included counties: {len(included)} of {len(excl)}.\n",
        "## Evaluation (test years)\n", md_table(ev), "\n",
        "## Top candidates (top quartile on residual and growth gap)\n",
        md_table(top[["county", "residual_pct", "growth_gap_log", "residual_rank", "growth_gap_rank"]]), "\n",
        "## Excluded counties\n",
        md_table(excl.loc[excl["excluded"], ["county", "hidden_quarter_share", "reason"]], ".2f"), "\n",
        "## 2022 NAICS switch check (statewide tire Q2/Q1)\n", md_table(transition), "\n",
        f"## Quarter-over-quarter outliers: {len(outliers)} county-quarters flagged "
        f"(|county - statewide QoQ log change| > {config.QOQ_OUTLIER_LOG}); see data/processed/qoq_outliers.csv\n",
    ]
    (config.REPORTS / "results_summary.md").write_text("\n".join(summary))

    print(f"\nincluded counties: {len(included)} / {len(excl)}")
    print(ev.to_string(index=False))
    print(ranked.head(10)[["county", "residual_pct", "growth_gap_log", "top_candidate"]].to_string(index=False))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-pull raw data instead of using data/raw/ caches")
    main(ap.parse_args().refresh)
